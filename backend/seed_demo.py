def seed() -> None:
    init_db()
    EXHIBIT_STORE.mkdir(exist_ok=True)

    created = []
    with get_conn() as conn:
        custody.init_custody_schema(conn)

        # Start from a clean demo set so reruns don't pile up duplicates.
        conn.execute("DELETE FROM custody_events")
        conn.execute("DELETE FROM checks")
        conn.execute("DELETE FROM exhibits")

        minute = 0
        for case in CASES:
            for spec in case["exhibits"]:
                content = spec["content"]()
                exhibit_id = custody.generate_exhibit_id(conn)
                dest = EXHIBIT_STORE / f"{exhibit_id}__{spec['filename']}"
                dest.write_bytes(content)

                sha256 = custody.sha256_file(dest)
                collected_at = _iso(BASE_TIME, minutes=minute)
                minute += 45

                conn.execute(
                    """INSERT INTO exhibits
                       (exhibit_id, case_id, description, collected_by, collected_role,
                        collected_place, collected_at, original_filename, filesize,
                        sha256, storage_path, created_at)
                       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                    (
                        exhibit_id, case["case_id"], spec["description"],
                        spec["collected_by"], spec["collected_role"],
                        spec["collected_place"], collected_at, spec["filename"],
                        len(content), sha256, str(dest), custody.now_iso(),
                    ),
                )

                custody.append_event(
                    conn, exhibit_id=exhibit_id, actor_name=spec["collected_by"],
                    actor_role=spec["collected_role"], action="COLLECTED",
                    note=spec["description"], occurred_at=collected_at,
                )
                for action, actor, role, extra, offset in spec["events"]:
                    custody.append_event(
                        conn, exhibit_id=exhibit_id, actor_name=actor, actor_role=role,
                        action=action,
                        from_person=extra.get("from_person"),
                        to_person=extra.get("to_person"),
                        note=extra.get("note"),
                        occurred_at=_iso(BASE_TIME, minutes=minute - 45 + offset),
                    )

                created.append((exhibit_id, case["case_id"], spec["filename"], sha256))

        # Confirm every seeded chain verifies before we claim success.
        for exhibit_id, *_ in created:
            status = custody.verify_chain(custody.load_events(conn, exhibit_id))
            if not status.ok:
                raise SystemExit(f"Seeded chain for {exhibit_id} is broken: {status.reason}")

    print(f"Seeded {len(created)} synthetic exhibits across {len(CASES)} cases.\n")
    for exhibit_id, case_id, filename, sha256 in created:
        print(f"  {exhibit_id}  {case_id:<16} {filename:<30} seal {sha256[:16]}…")
    print("\nAll custody chains verified intact.")
    print("Start the API with:  uvicorn app.main:app --reload --port 8000")
    print("Then open public/exhibits.html and pick any exhibit to run the tamper demo.")


if __name__ == "__main__":
    seed()
