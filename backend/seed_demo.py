def make_png(width: int = 96, height: int = 96) -> bytes:
    """A small valid PNG with a simple pattern, written by hand (zlib only)."""
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter: none
        for x in range(width):
            r = (x * 255) // max(1, width - 1)
            g = (y * 255) // max(1, height - 1)
            b = 120 if ((x // 12) + (y // 12)) % 2 == 0 else 60
            raw += bytes((r, g, b))

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header)
            + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))


def make_log_file() -> bytes:
    base = datetime(2026, 1, 4, 17, 0, tzinfo=timezone.utc)
    lines = ["# SYNTHETIC device log - generated for a demonstration"]
    for i in range(60):
        t = (base + timedelta(seconds=i * 37)).strftime("%Y-%m-%dT%H:%M:%SZ")
        level = "INFO" if i % 7 else "WARN"
        lines.append(f"{t} {level} pump.station6 pressure={2.4 + (i % 9) * 0.05:.2f}bar")
    return ("\n".join(lines) + "\n").encode("utf-8")


